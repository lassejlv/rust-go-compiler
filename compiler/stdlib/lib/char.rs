    #[inline]
    pub const fn from_u32(i: u32) -> Option<char> {
        from_u32(i)
    }

    /// Converts a `u32` to a `char`, ignoring validity.
    #[inline]
    pub const unsafe fn from_u32_unchecked(i: u32) -> char {
        from_u32_unchecked(i)
    }

    /// Creates an iterator over the UTF-16 encoded code points in `iter`,
    /// returning unpaired surrogates as `Err`s.
    #[inline]
    pub fn decode_utf16<I: crate::iter::IntoIterator<Item = u16>>(iter: I) -> DecodeUtf16<I::IntoIter> {
        decode_utf16(iter)
    }

    /// Converts a digit in the given radix to a `char`.
    #[inline]
    pub fn from_digit(num: u32, radix: u32) -> Option<char> {
        from_digit(num, radix)
    }

    /// Checks if a `char` is a digit in the given radix.
    #[inline]
    pub fn is_digit(self, radix: u32) -> bool {
        self.to_digit(radix).is_some()
    }

    /// Converts a `char` to a digit in the given radix.
    #[inline]
    pub fn to_digit(self, radix: u32) -> Option<u32> {
        if radix < 2 || radix > 36 {
            crate::rt::panic_str("to_digit: invalid radix -- radix must be in the range 2 to 36 inclusive", file!(), line!(), column!());
        }
        let c = self as u32;
        let digit = if c >= 0x30 && c <= 0x39 {
            c - 0x30
        } else if c >= 0x61 && c <= 0x7A {
            c - 0x61 + 10
        } else if c >= 0x41 && c <= 0x5A {
            c - 0x41 + 10
        } else {
            return None;
        };
        if digit < radix {
            Some(digit)
        } else {
            None
        }
    }

    /// Returns an iterator that yields the hexadecimal Unicode escape of a character as `char`s.
    #[inline]
    pub fn escape_unicode(self) -> EscapeUnicode {
        EscapeUnicode { inner: EscapeBuf::unicode(self as u32) }
    }

    /// Returns an iterator that yields the literal escape code of a character as `char`s.
    #[inline]
    pub fn escape_debug(self) -> EscapeDebug {
        EscapeDebug { inner: EscapeBuf::debug(self, true, true, true) }
    }

    /// Returns an iterator that yields the literal escape code of a character as `char`s.
    #[inline]
    pub fn escape_default(self) -> EscapeDefault {
        let c = self as u32;
        let inner = match self {
            '\t' => EscapeBuf::backslash(b't'),
            '\r' => EscapeBuf::backslash(b'r'),
            '\n' => EscapeBuf::backslash(b'n'),
            '\\' | '\'' | '"' => EscapeBuf::backslash(c as u8),
            _ => {
                if c >= 0x20 && c <= 0x7E {
                    EscapeBuf::printable(self)
                } else {
                    EscapeBuf::unicode(c)
                }
            }
        };
        EscapeDefault { inner }
    }

    /// Returns the number of bytes this `char` would need if encoded in UTF-8.
    #[inline]
    pub const fn len_utf8(self) -> usize {
        len_utf8_raw(self as u32)
    }

    /// Returns the number of 16-bit code units this `char` would need if encoded in UTF-16.
    #[inline]
    pub const fn len_utf16(self) -> usize {
        if (self as u32) < 0x10000 {
            1
        } else {
            2
        }
    }

    /// Encodes this character as UTF-8 into the provided byte buffer, and then returns the subslice of the buffer that contains the encoded character.
    #[inline]
    pub fn encode_utf8(self, dst: &mut [u8]) -> &mut str {
        let len = self.len_utf8();
        if dst.len() < len {
            crate::rt::panic_fmt(
                format_args!(
                    "encode_utf8: need {} bytes to encode U+{:X}, but the buffer has {}",
                    len,
                    self as u32,
                    dst.len()
                ),
                file!(),
                line!(),
                column!(),
            );
        }
        unsafe {
            let p = dst.as_mut_ptr();
            encode_utf8_raw(self as u32, p);
            &mut *(intrinsics::str_from_raw_parts(p as *const u8, len) as *mut str)
        }
    }

    /// Encodes this character as UTF-16 into the provided `u16` buffer, and then returns the subslice of the buffer that contains the encoded character.
    #[inline]
    pub fn encode_utf16(self, dst: &mut [u16]) -> &mut [u16] {
        let mut code = self as u32;
        if code < 0x10000 {
            dst[0] = code as u16;
            &mut dst[..1]
        } else {
            code -= 0x10000;
            dst[0] = 0xD800 | ((code >> 10) as u16);
            dst[1] = 0xDC00 | ((code as u16) & 0x3FF);
            &mut dst[..2]
        }
    }

    /// Returns `true` if this `char` has the `Alphabetic` property.
    #[inline]
    pub fn is_alphabetic(self) -> bool {
        let c = self as u32;
        if c < 0x80 {
            return (c >= 0x41 && c <= 0x5A) || (c >= 0x61 && c <= 0x7A);
        }
        in_table(&ALPHABETIC, c)
    }

    /// Returns `true` if this `char` has the `Lowercase` property.
    #[inline]
    pub fn is_lowercase(self) -> bool {
        let c = self as u32;
        if c < 0x80 {
            return c >= 0x61 && c <= 0x7A;
        }
        in_table(&LOWERCASE, c)
    }

    /// Returns `true` if this `char` has the `Uppercase` property.
    #[inline]
    pub fn is_uppercase(self) -> bool {
        let c = self as u32;
        if c < 0x80 {
            return c >= 0x41 && c <= 0x5A;
        }
        in_table(&UPPERCASE, c)
    }

    /// Returns `true` if this `char` has the `White_Space` property.
    #[inline]
    pub fn is_whitespace(self) -> bool {
        match self {
            ' ' | '\x09'..='\x0d' => true,
            c => {
                let c = c as u32;
                c > 0x7f
                    && (c == 0x85
                        || c == 0xA0
                        || c == 0x1680
                        || (c >= 0x2000 && c <= 0x200A)
                        || c == 0x2028
                        || c == 0x2029
                        || c == 0x202F
                        || c == 0x205F
                        || c == 0x3000)
            }
        }
    }

    /// Returns `true` if this `char` satisfies either `is_alphabetic()` or `is_numeric()`.
    #[inline]
    pub fn is_alphanumeric(self) -> bool {
        self.is_alphabetic() || self.is_numeric()
    }

    /// Returns `true` if this `char` has the general category for control codes.
    #[inline]
    pub fn is_control(self) -> bool {
        let c = self as u32;
        c < 0x20 || (c >= 0x7F && c <= 0x9F)
    }

    /// Returns `true` if this `char` has one of the general categories for numbers.
    #[inline]
    pub fn is_numeric(self) -> bool {
        let c = self as u32;
        if c < 0x80 {
            return c >= 0x30 && c <= 0x39;
        }
        in_table(&NUMERIC, c)
    }

    /// Returns an iterator that yields the lowercase mapping of this `char` as one or more `char`s.
    #[inline]
    pub fn to_lowercase(self) -> ToLowercase {
        let c = self as u32;
        if c >= 0x80 {
            if let Some(m) = multi_lookup(&LOWER_MULTI, c) {
                return ToLowercase(mapping_iter(m));
            }
        }
        ToLowercase(CaseMappingIter::new1(to_char(lower_map(c))))
    }

    /// Returns an iterator that yields the uppercase mapping of this `char` as one or more `char`s.
    #[inline]
    pub fn to_uppercase(self) -> ToUppercase {
        let c = self as u32;
        if c >= 0x80 {
            if let Some(m) = multi_lookup(&UPPER_MULTI, c) {
                return ToUppercase(mapping_iter(m));
            }
        }
        ToUppercase(CaseMappingIter::new1(to_char(upper_map(c))))
    }

    /// Checks if the value is within the ASCII range.
    #[inline]
    pub const fn is_ascii(&self) -> bool {
        (*self as u32) <= 0x7F
    }

    /// Returns `Some` if the value is within the ASCII range, or `None` if it's not.
