#[inline]
fn in_table(table: &[(u32, u32)], c: u32) -> bool {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let (a, b) = table[mid];
        if c < a {
            hi = mid;
        } else if c > b {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    false
}

/// Looks up a single-character case mapping (runs of `(start, end, delta, step)`).
#[inline]
fn case_lookup(table: &[(u32, u32, i32, u32)], c: u32) -> u32 {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let (a, b, delta, step) = table[mid];
        if c < a {
            hi = mid;
        } else if c > b {
            lo = mid + 1;
        } else {
            if (c - a) % step == 0 {
                return ((c as i64) + (delta as i64)) as u32;
            }
            return c;
        }
    }
    c
}

/// Looks up a multi-character case mapping.
#[inline]
fn multi_lookup(table: &[(u32, [u32; 3])], c: u32) -> Option<[u32; 3]> {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let (a, m) = table[mid];
        if c < a {
            hi = mid;
        } else if c > a {
            lo = mid + 1;
        } else {
            return Some(m);
        }
    }
    None
}

pub(crate) fn is_grapheme_extended(c: char) -> bool {
    let c = c as u32;
    c >= 0x300 && in_table(&GRAPHEME_EXTEND, c)
}

/// Returns `true` if `escape_debug` prints `c` as a `\u{..}` escape.
#[inline]
fn needs_unicode_escape(c: char) -> bool {
    let c = c as u32;
    if c >= 0x20 && c < 0x7F {
        return false;
    }
    in_table(&ESCAPE_UNICODE, c)
}

pub(crate) fn is_printable(c: char) -> bool {
    !needs_unicode_escape(c) || is_grapheme_extended(c)
}

#[inline]
fn lower_map(c: u32) -> u32 {
    if c < 0x80 {
        return if c >= 0x41 && c <= 0x5A { c + 32 } else { c };
    }
    case_lookup(&LOWER_MAP, c)
}

#[inline]
fn upper_map(c: u32) -> u32 {
    if c < 0x80 {
        return if c >= 0x61 && c <= 0x7A { c - 32 } else { c };
    }
    case_lookup(&UPPER_MAP, c)
}

#[inline]
fn to_char(c: u32) -> char {
    unsafe { from_u32_unchecked(c) }
}

#[inline]
fn mapping_iter(m: [u32; 3]) -> CaseMappingIter {
    let n = if m[2] != 0 { 3 } else if m[1] != 0 { 2 } else { 1 };
    CaseMappingIter { chars: [to_char(m[0]), to_char(m[1]), to_char(m[2])], start: 0, end: n }
}

