#[derive(Clone, Debug)]
struct CaseMappingIter {
    chars: [char; 3],
    start: usize,
    end: usize,
}

impl CaseMappingIter {
    fn new1(c: char) -> CaseMappingIter {
        CaseMappingIter { chars: [c, '\0', '\0'], start: 0, end: 1 }
    }
    fn next(&mut self) -> Option<char> {
        if self.start < self.end {
            let c = self.chars[self.start];
            self.start += 1;
            Some(c)
        } else {
            None
        }
    }
    fn next_back(&mut self) -> Option<char> {
        if self.start < self.end {
            self.end -= 1;
            Some(self.chars[self.end])
        } else {
            None
        }
    }
    fn len(&self) -> usize {
        self.end - self.start
    }
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut i = self.start;
        while i < self.end {
            f.write_char(self.chars[i])?;
            i += 1;
        }
        Ok(())
    }
}

/// Returns an iterator that yields the uppercase equivalent of a `char`.
#[derive(Clone, Debug)]
pub struct ToUppercase(CaseMappingIter);

/// Returns an iterator that yields the lowercase equivalent of a `char`.
#[derive(Clone, Debug)]
pub struct ToLowercase(CaseMappingIter);

macro_rules! __std_char_case_iter {
    ($($name:ident)*) => {
        $(
            impl Iterator for $name {
                type Item = char;
                #[inline]
                fn next(&mut self) -> Option<char> {
                    self.0.next()
                }
                #[inline]
                fn size_hint(&self) -> (usize, Option<usize>) {
                    let n = self.0.len();
                    (n, Some(n))
                }
            }
            impl DoubleEndedIterator for $name {
                #[inline]
                fn next_back(&mut self) -> Option<char> {
                    self.0.next_back()
                }
            }
            impl ExactSizeIterator for $name {}
            impl FusedIterator for $name {}
            impl fmt::Display for $name {
                fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                    self.0.fmt(f)
                }
            }
        )*
    };
}

