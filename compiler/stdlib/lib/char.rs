/// The highest valid code point a `char` can have, `'\u{10FFFF}'`.
pub const MAX: char = '\u{10FFFF}';

/// `U+FFFD REPLACEMENT CHARACTER` (�).
pub const REPLACEMENT_CHARACTER: char = '\u{FFFD}';

/// Converts a `u32` to a `char`.
#[inline]
pub const fn from_u32(i: u32) -> Option<char> {
    if i > 0x10FFFF || (i >= 0xD800 && i <= 0xDFFF) {
        None
    } else {
        Some(unsafe { intrinsics::transmute::<u32, char>(i) })
    }
}

/// Converts a `u32` to a `char`, ignoring validity.
#[inline]
pub const unsafe fn from_u32_unchecked(i: u32) -> char {
    intrinsics::transmute::<u32, char>(i)
}

/// Converts a digit in the given radix to a `char`.
#[inline]
pub fn from_digit(num: u32, radix: u32) -> Option<char> {
    if radix > 36 {
        crate::rt::panic_str("from_digit: radix is too high (maximum 36)", file!(), line!(), column!());
    }
    if num < radix {
        let num = num as u8;
        if num < 10 {
            Some((b'0' + num) as char)
        } else {
            Some((b'a' + num - 10) as char)
        }
    } else {
        None
    }
}

/// Encodes a code point as UTF-8 into `dst` (which must have room for 4
/// bytes) and returns the number of bytes written.
#[inline]
pub(crate) unsafe fn encode_utf8_raw(code: u32, dst: *mut u8) -> usize {
    if code < 0x80 {
        *dst = code as u8;
        1
    } else if code < 0x800 {
        *dst = (0xC0 | (code >> 6)) as u8;
        *dst.add(1) = (0x80 | (code & 0x3F)) as u8;
        2
    } else if code < 0x10000 {
        *dst = (0xE0 | (code >> 12)) as u8;
        *dst.add(1) = (0x80 | ((code >> 6) & 0x3F)) as u8;
        *dst.add(2) = (0x80 | (code & 0x3F)) as u8;
        3
    } else {
        *dst = (0xF0 | (code >> 18)) as u8;
        *dst.add(1) = (0x80 | ((code >> 12) & 0x3F)) as u8;
        *dst.add(2) = (0x80 | ((code >> 6) & 0x3F)) as u8;
        *dst.add(3) = (0x80 | (code & 0x3F)) as u8;
        4
    }
}

/// Number of bytes needed to encode a code point as UTF-8.
#[inline]
pub(crate) const fn len_utf8_raw(code: u32) -> usize {
    if code < 0x80 {
        1
    } else if code < 0x800 {
        2
    } else if code < 0x10000 {
        3
    } else {
        4
    }
}

