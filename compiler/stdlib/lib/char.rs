#[derive(Clone, Debug)]
struct EscapeBuf {
    // Either a single printable char (`ch` with `is_char`), or ASCII bytes in `buf[start..end]`.
    is_char: bool,
    ch: char,
    buf: [u8; 12],
    start: usize,
    end: usize,
}

impl EscapeBuf {
    fn printable(c: char) -> EscapeBuf {
        EscapeBuf { is_char: true, ch: c, buf: [0; 12], start: 0, end: 1 }
    }

    fn backslash(b: u8) -> EscapeBuf {
        let mut buf = [0u8; 12];
        buf[0] = b'\\';
        buf[1] = b;
        EscapeBuf { is_char: false, ch: '\0', buf, start: 0, end: 2 }
    }

    fn unicode(c: u32) -> EscapeBuf {
        let mut buf = [0u8; 12];
        buf[0] = b'\\';
        buf[1] = b'u';
        buf[2] = b'{';
        // number of hex digits
        let mut digits = 1;
        let mut t = c >> 4;
        while t != 0 {
            digits += 1;
            t >>= 4;
        }
        let mut i = 0;
        while i < digits {
            let d = ((c >> (4 * (digits - 1 - i) as u32)) & 0xF) as u8;
            buf[3 + i] = if d < 10 { b'0' + d } else { b'a' + d - 10 };
            i += 1;
        }
        buf[3 + digits] = b'}';
        EscapeBuf { is_char: false, ch: '\0', buf, start: 0, end: 4 + digits }
    }

    fn debug(c: char, grapheme: bool, single_quote: bool, double_quote: bool) -> EscapeBuf {
        match c {
            '\0' => EscapeBuf::backslash(b'0'),
            '\t' => EscapeBuf::backslash(b't'),
            '\r' => EscapeBuf::backslash(b'r'),
            '\n' => EscapeBuf::backslash(b'n'),
            '\\' => EscapeBuf::backslash(b'\\'),
            '"' if double_quote => EscapeBuf::backslash(b'"'),
            '\'' if single_quote => EscapeBuf::backslash(b'\''),
            _ => {
                if needs_unicode_escape(c) && (grapheme || !is_grapheme_extended(c)) {
                    EscapeBuf::unicode(c as u32)
                } else {
                    EscapeBuf::printable(c)
                }
            }
        }
    }

    fn is_unchanged(&self) -> bool {
        self.is_char
    }

    fn next(&mut self) -> Option<char> {
        if self.start >= self.end {
            return None;
        }
        if self.is_char {
            self.start += 1;
            Some(self.ch)
        } else {
            let b = self.buf[self.start];
            self.start += 1;
            Some(b as char)
        }
    }

    fn len(&self) -> usize {
        self.end - self.start
    }

    fn write_to(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.is_char {
            if self.start < self.end {
                f.write_char(self.ch)?;
            }
            Ok(())
        } else {
            let mut i = self.start;
            while i < self.end {
                f.write_char(self.buf[i] as char)?;
                i += 1;
            }
            Ok(())
        }
    }
}

/// Writes the Debug escape of `c` (as used inside string/char literals).
#[inline]
pub(crate) fn write_escape_debug(
    f: &mut fmt::Formatter<'_>,
    c: char,
    single_quote: bool,
    double_quote: bool,
) -> fmt::Result {
    let e = EscapeBuf::debug(c, true, single_quote, double_quote);
    e.write_to(f)
}

/// Returns whether `c` must be escaped in a Debug string literal.
#[inline]
pub(crate) fn needs_debug_escape(c: char, single_quote: bool, double_quote: bool) -> bool {
    !EscapeBuf::debug(c, true, single_quote, double_quote).is_unchanged()
}

