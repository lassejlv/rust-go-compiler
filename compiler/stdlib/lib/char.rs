/// The error type returned when a conversion from `u32` to `char` fails.
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub struct CharTryFromError(());

impl fmt::Display for CharTryFromError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.pad("converted integer out of range for `char`")
    }
}

impl crate::error::Error for CharTryFromError {}

impl TryFrom<u32> for char {
    type Error = CharTryFromError;
    #[inline]
    fn try_from(i: u32) -> Result<char, CharTryFromError> {
        match from_u32(i) {
            Some(c) => Ok(c),
            None => Err(CharTryFromError(())),
        }
    }
}

/// The error type returned when a checked char conversion fails.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub struct TryFromCharError(pub(crate) ());

impl fmt::Display for TryFromCharError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.pad("unicode code point out of range")
    }
}

impl crate::error::Error for TryFromCharError {}

impl TryFrom<char> for u8 {
    type Error = TryFromCharError;
    #[inline]
    fn try_from(c: char) -> Result<u8, TryFromCharError> {
        let c = c as u32;
        if c <= 0xFF {
            Ok(c as u8)
        } else {
            Err(TryFromCharError(()))
        }
    }
}

impl TryFrom<char> for u16 {
    type Error = TryFromCharError;
    #[inline]
    fn try_from(c: char) -> Result<u16, TryFromCharError> {
        let c = c as u32;
        if c <= 0xFFFF {
            Ok(c as u16)
        } else {
            Err(TryFromCharError(()))
        }
    }
}

/// An error which can be returned when parsing a char.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ParseCharError {
    kind: CharErrorKind,
}

#[derive(Copy, Clone, Debug, PartialEq, Eq)]
enum CharErrorKind {
    EmptyString,
    TooManyChars,
}

impl fmt::Display for ParseCharError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.kind {
            CharErrorKind::EmptyString => f.pad("cannot parse char from empty string"),
            CharErrorKind::TooManyChars => f.pad("too many characters in string"),
        }
    }
}

impl crate::error::Error for ParseCharError {}

impl FromStr for char {
    type Err = ParseCharError;
    #[inline]
    fn from_str(s: &str) -> Result<char, ParseCharError> {
        let mut chars = s.chars();
        match (chars.next(), chars.next()) {
            (None, _) => Err(ParseCharError { kind: CharErrorKind::EmptyString }),
            (Some(c), None) => Ok(c),
            _ => Err(ParseCharError { kind: CharErrorKind::TooManyChars }),
        }
    }
}

/// An iterator that decodes UTF-16 encoded code points from an iterator of `u16`s.
#[derive(Clone, Debug)]
pub struct DecodeUtf16<I> {
    iter: I,
    buf: Option<u16>,
}

/// An error that can be returned when decoding UTF-16 code points.
#[derive(Debug, Clone, Eq, PartialEq)]
pub struct DecodeUtf16Error {
    code: u16,
}

impl DecodeUtf16Error {
    /// Returns the unpaired surrogate which caused this error.
    pub fn unpaired_surrogate(&self) -> u16 {
        self.code
    }
}

impl crate::error::Error for DecodeUtf16Error {}

impl fmt::Display for DecodeUtf16Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "unpaired surrogate found: {:x}", self.code)
    }
}

/// Creates an iterator over the UTF-16 encoded code points in `iter`, returning unpaired surrogates as `Err`s.
pub fn decode_utf16<I: crate::iter::IntoIterator<Item = u16>>(iter: I) -> DecodeUtf16<I::IntoIter> {
    DecodeUtf16 { iter: iter.into_iter(), buf: None }
}

impl<I: Iterator<Item = u16>> Iterator for DecodeUtf16<I> {
    type Item = Result<char, DecodeUtf16Error>;
    fn next(&mut self) -> Option<Result<char, DecodeUtf16Error>> {
        let u = match self.buf.take() {
            Some(buf) => buf,
            None => match self.iter.next() {
                Some(u) => u,
                None => return None,
            },
        };
        if (u & 0xF800) != 0xD800 {
            Some(Ok(unsafe { from_u32_unchecked(u as u32) }))
        } else if u >= 0xDC00 {
            Some(Err(DecodeUtf16Error { code: u }))
        } else {
            let u2 = match self.iter.next() {
                Some(u2) => u2,
                None => return Some(Err(DecodeUtf16Error { code: u })),
            };
            if u2 < 0xDC00 || u2 > 0xDFFF {
                self.buf = Some(u2);
                return Some(Err(DecodeUtf16Error { code: u }));
            }
            let c = (((u & 0x3ff) as u32) << 10 | (u2 & 0x3ff) as u32) + 0x1_0000;
            Some(Ok(unsafe { from_u32_unchecked(c) }))
        }
    }
}
