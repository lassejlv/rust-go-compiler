fn main() {
    let x = 3.14159265358979f64;
    println!("{:.3} {:.0} {:8.2}| {:<8.1}| {:+.2}", x, x, x, x, x);
    println!("{:e} {:E}", 1234.5f64, 0.00012f64);
    println!("{:e} {:.2e}", 1e100f64, 123456.0f64);
    println!("{:e}", 0.0f64);
    let a = 0.1f32 + 0.2f32;
    let b = 0.1f64 + 0.2f64;
    println!("{} {}", a, b);
    println!("{} {}", a == 0.3f32, b == 0.3f64);
    println!("{} {}", 1.0f32 / 3.0, 1.0f64 / 3.0);
    println!("{:?} {:?}", 1.0f64, 1.5e300 * 1e10);
    println!("{} {}", f32::MAX, f32::MIN_POSITIVE);
    println!("{} {}", f64::EPSILON, f32::EPSILON);
    println!("{:#x} {:#x}", 1.0f32.to_bits(), (-2.5f64).to_bits());
    println!("{}", f32::from_bits(0x40490fdb));
    println!("{}", f64::from_bits(0x3ff8000000000000));
    let nan = f64::NAN;
    println!("{} {} {} {}", nan == nan, nan < 1.0, nan > 1.0, nan != nan);
    println!("{} {}", nan.is_nan(), (0.0f64 / 0.0).is_nan());
    println!("{:?} {:?}", nan.partial_cmp(&1.0), 1.0f64.partial_cmp(&2.0));
    println!("{:?}", f64::NAN.total_cmp(&f64::INFINITY));
    println!("{:?}", (-0.0f64).total_cmp(&0.0));
    println!("{}", -0.0f64 == 0.0);
    let mut v = vec![2.0, f64::NAN, -1.0, f64::NEG_INFINITY, 0.5];
    v.sort_by(|a, b| a.total_cmp(b));
    println!("{:?}", v);
    println!("{} {}", 1.0f64.max(f64::NAN), f64::NAN.min(3.0));
    println!("{} {} {}", 15.7f64.clamp(0.0, 10.0), (-3.0f64).clamp(-1.0, 1.0), 0.5f64.clamp(0.0, 1.0));
    println!("{} {} {} {}", 2.5f64.round(), -2.5f64.round(), 2.5f64.floor(), -2.5f64.ceil());
    println!("{} {}", 7.9f64.trunc(), -7.9f64.fract());
    println!("{} {}", 2.0f64.sqrt(), 2.0f32.sqrt());
    println!("{:.6} {:.6}", 1.0f64.exp(), std::f64::consts::PI.sin().abs());
    println!("{} {}", 2.0f64.powi(10), 2.0f64.powf(0.5));
    println!("{} {}", 100.0f64.log10(), 8.0f64.log2());
    println!("{:.4} {:.4}", 1.0f64.atan2(1.0), 0.5f64.acos());
    println!("{} {}", 1.0f64.hypot(1.0), (-8.0f64).cbrt());
    println!("{} {} {}", f64::INFINITY, -f64::INFINITY, f64::NAN);
    println!("{:?} {:?}", 1e15f64, 1e16f64);
    println!("{} {}", 1e15f64, 1e16f64);
    println!("{} {} {}", 0.000001f64, 1e-7f64, 123456789.0f32);
    println!("{:?} {:?}", 0.1f32 as f64, 0.1f64 as f32);
    println!("{:10.3}|{:<10.3}|{:^10.3}|{:010.3}", -1.5, 2.25, 3.125, -4.0);
    println!("{:?}", "3.5e2".parse::<f64>());
    println!("{:?} {:?}", "inf".parse::<f64>(), "abc".parse::<f32>().is_err());
    println!("{} {}", 5.0f64.mul_add(2.0, 1.0), 10.0f64.recip());
    println!("{} {}", (1.0f64).copysign(-0.0), 9.0f64.to_degrees() > 500.0);
    println!("{} {}", 1.0f64.is_sign_positive(), (-0.0f64).is_sign_negative());
    let total: f32 = [0.1f32; 10].iter().sum();
    println!("{} {:.7}", total, total);
    println!("{}", f64::MAX);
    println!("{:?}", 5e-324f64);
}
