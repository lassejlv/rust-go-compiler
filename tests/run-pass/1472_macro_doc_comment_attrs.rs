#![allow(unused_doc_comments)]
// doc comments inside macro definitions and invocations become #[doc] attributes
macro_rules! documented_struct {
    ($(#[$m:meta])* $name:ident { $($(#[$fm:meta])* $f:ident: $t:ty),* $(,)? }) => {
        $(#[$m])*
        #[derive(Debug, Default)]
        /// Generated struct.
        pub struct $name {
            $( $(#[$fm])* pub $f: $t, )*
        }
        impl $name {
            /// Returns the docs.
            pub fn docs() -> Vec<&'static str> {
                let mut v = Vec::new();
                $( v.push(stringify!($m)); )*
                v
            }
        }
    };
}

documented_struct! {
    /// A point in space.
    /// Second line with "quotes".
    #[derive(Clone)]
    Point {
        /// x coordinate
        x: i32,
        /** y coordinate */
        y: i32,
    }
}

macro_rules! help_table {
    ($( $(#[doc = $doc:literal])+ $cmd:ident ),* $(,)?) => {
        &[ $( (stringify!($cmd), concat!($($doc, "\n"),+)) ),* ]
    };
}

macro_rules! body_with_docs {
    () => {{
        /// doc on a let
        let a = 1;
        /// doc on an expression statement
        let b = match a {
            /// doc on an arm
            1 => 10,
            _ => 0,
        };
        a + b
    }};
}

/// Enum with documented variants generated by a macro.
macro_rules! documented_enum {
    ($name:ident { $($(#[$m:meta])* $v:ident),* }) => {
        #[derive(Debug)]
        enum $name { $($(#[$m])* $v),* }
        impl $name {
            fn count() -> usize { [$(stringify!($v)),*].len() }
        }
    };
}
documented_enum!(Color {
    /// red
    Red,
    // plain comment
    Green,
    /// blue
    Blue
});

trait Shape {
    /// area
    fn area(&self) -> f64;
}

macro_rules! impl_shape {
    ($t:ident, $e:expr) => {
        impl Shape for $t {
            /// computed area
            fn area(&self) -> f64 { $e(self) }
        }
    };
}
struct Sq(f64);
impl_shape!(Sq, |s: &Sq| s.0 * s.0);

fn main() {
    let p = Point { x: 1, y: 2 }.clone();
    println!("{:?}", p);
    for d in Point::docs() { println!("{}", d); }
    let t: &[(&str, &str)] = help_table! {
        /// Shows help.
        /// More help.
        help,
        /// Quits.
        quit,
    };
    for (c, d) in t { print!("{}: {}", c, d); }
    println!("{}", body_with_docs!());
    println!("{} {:?}", Color::count(), Color::Blue);
    println!("{}", Sq(3.0).area());
    let v = vec![
        1,
        2,
    ];
    println!("{:?}", v);
}
