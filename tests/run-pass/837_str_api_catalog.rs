fn main() {
    let s = "Mary had a little lamb, little lamb, little lamb";
    println!("{:?}", s.match_indices("lamb").collect::<Vec<_>>());
    println!("{:?}", s.rmatch_indices("little").map(|(i, _)| i).collect::<Vec<_>>());
    println!("{:?}", s.split_inclusive(',').collect::<Vec<_>>());
    println!("{:?}", "a,b,,c,".split_terminator(',').collect::<Vec<_>>());
    println!("{:?}", "a,b,,c,".rsplit_terminator(',').collect::<Vec<_>>());
    println!("{:?}", s.rsplitn(3, ' ').collect::<Vec<_>>());
    println!("{:?}", s.splitn(3, |c: char| c == 'a' || c == 'e').collect::<Vec<_>>());
    println!("{:?}", "xxabcxx".trim_start_matches('x').trim_end_matches("xx"));
    println!("{:?}", "123abc456".trim_matches(char::is_numeric));
    println!("{:?}", "  a b  ".split(' ').collect::<Vec<_>>());
    println!("{:?}", "a\tb\n c".split_ascii_whitespace().collect::<Vec<_>>());
    println!("{:?} {:?}", s.find(&['h', 'l'][..]), s.rfind(|c: char| c.is_uppercase()));
    println!("{:?} {:?}", s.rsplit_once(", "), "k:v:w".split_once(':'));
    println!("{}", s.replacen("lamb", "goat", 2));
    println!("{:?}", "Hello World".char_indices().rev().nth(2));
    println!("{:?}", "abc".chars().rev().eq("cba".chars()));
    println!("{:?}", "ab".chars().cmp("b".chars()));
    let mut st = String::from("hello world");
    st.replace_range(0..5, "HOWDY");
    st.insert_str(5, ",");
    st.retain(|c| c != 'o');
    let popped = st.pop();
    let rem = st.remove(0);
    println!("{} {:?} {}", st, popped, rem);
    let dr: String = st.drain(..3).collect();
    println!("{} | {}", dr, st);
    let mut a = String::from("abcdef"); let b = a.split_off(4); println!("{} {}", a, b);
    println!("{:?}", "ß".to_uppercase());
    println!("{:?}", "İ".to_lowercase().chars().count());
    println!("{:?}", "ΌΣΟΣ".to_lowercase());
    println!("{:?}", "  x  ".trim_ascii());
    println!("{:?}", b"  x  ".trim_ascii_start());
    println!("{:?}", "abc".bytes().rev().collect::<Vec<u8>>());
    println!("{:?}", "a-b_c".split(['-', '_']).collect::<Vec<_>>());
    println!("{:?}", "a-b_c".split(&['-', '_'][..]).count());
    println!("{:?}", "aXbYc".split(char::is_uppercase).collect::<Vec<_>>());
    println!("{:?}", "one two".contains(char::is_whitespace));
    println!("{:?}", "hello".starts_with(|c: char| c == 'h'));
    println!("{:?}", "hello".strip_suffix("lo").and_then(|s| s.strip_prefix('h')));
    println!("{:?}", "x=1;y=2".split(';').map(|kv| kv.split('=').collect::<Vec<_>>()).collect::<Vec<_>>());
    println!("{:?}", "AbC".chars().map(|c| if c.is_uppercase() { c.to_ascii_lowercase() } else { c.to_ascii_uppercase() }).collect::<String>());
    println!("{:?}", "abc".char_indices().map(|(i, c)| format!("{}{}", i, c)).collect::<Vec<_>>().concat());
    println!("{:?}", "lines\nwith\r\nendings\n".lines().collect::<Vec<_>>());
    println!("{:?}", "tab\tsep".escape_default().to_string());
    println!("{:?}", String::from_utf8(vec![0xe2, 0x82, 0xac]).unwrap());
    println!("{:?}", "héllo".get(1..3));
    println!("{:?}", "héllo".get(1..2));
    println!("{:?}", "abc".as_bytes().iter().rposition(|&b| b == b'a'));
    println!("{:?}", "a".repeat(3) + &"b".repeat(2));
    let words = vec!["x", "y", "z"];
    println!("{} {}", words.concat(), words.join("/"));
    println!("{:?}", "Hello".chars().filter(char::is_ascii_lowercase).count());
    println!("{:?}", "abc".parse::<String>());
    println!("{:?}", "a b c".split(' ').rev().collect::<Vec<_>>().join(" "));
    println!("{:?}", "abcdef".char_indices().step_by(2).map(|(_, c)| c).collect::<String>());
    println!("{:?}", "The Cat".to_lowercase().split(' ').map(|w| w.chars().rev().collect::<String>()).collect::<Vec<_>>());
    println!("{}", "ab".cmp("abc") as i8);
    println!("{:?}", "z".partial_cmp("a"));
    println!("{:?}", ["b", "a", "C"].iter().max());
    let mut v = vec!["banana", "Apple", "cherry", "apple"];
    v.sort_by_key(|s| s.to_lowercase());
    println!("{:?}", v);
    v.sort_by(|a, b| b.len().cmp(&a.len()).then_with(|| a.cmp(b)));
    println!("{:?}", v);
    println!("{:?}", "%41%42".split('%').filter(|s| !s.is_empty()).map(|h| u8::from_str_radix(h, 16).unwrap() as char).collect::<String>());
    println!("{:?}", "abc".chars().map(|c| ((c as u8) ^ 0x20) as char).collect::<String>());
    println!("{:?}", char::from_u32('a' as u32 + 2));
    println!("{:?}", ('a'..='e').rev().step_by(2).collect::<String>());
    println!("{:?}", "a😀b".chars().map(char::len_utf8).collect::<Vec<_>>());
    println!("{:?}", "a😀b".encode_utf16().count());
    println!("{:?}", std::str::from_utf8(&[0xf0, 0x9f, 0x98]).map_err(|e| e.to_string()));
    println!("{:?}", String::from_utf8(vec![b'a', 0xc0, b'b']).map_err(|e| e.to_string()));
    println!("{:?}", String::from_utf16(&[0xd800]).map_err(|e| e.to_string()));
    println!("{:?}", String::from_utf16_lossy(&[0x61, 0xd800, 0x62]));
    println!("{:?}", char::decode_utf16([0x61, 0xdc00, 0xd83d, 0xde00]).map(|r| r.map_err(|e| e.unpaired_surrogate())).collect::<Vec<_>>());
}
